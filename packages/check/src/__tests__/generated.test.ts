// A generated module is not held to how its source is written; every rule about what it does still applies.

import { describe, expect, test } from 'bun:test'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import type { Finding } from '../finding'
import { check } from './helpers'

/** The exact output of `@buzola/codegen` 0.0.28 for a routes directory of a layout, two pages and a not-found page. */
const BUZOLA_GEN = readFileSync(join(import.meta.dir, 'fixtures', 'buzola.gen.ts.fixture'), 'utf8')

const HEADER = '// @generated by a generator. Do not edit.\n'

/** Written the way a generator writes: a cast, `any`, a suppression comment for a linter, and a hint's data access. */
const STYLE_ONLY = "// eslint-disable-next-line\nexport const parsed = JSON.parse('1') as number\nexport const loose: any = parsed\n"
	+ 'export const read = (ctx: { db: unknown }) => ctx.db\n'

const described = (findings: readonly Finding[]): string[] =>
	findings.map((finding) => `${finding.file}:${finding.line}:${finding.column} ${finding.rule}`)

describe('generated modules', () => {
	test('a generated module is not held to type-assertion, any-type, suppression-comment or the hints', async () => {
		const files = {
			'src/reports/view.gen.ts': `${HEADER}${STYLE_ONLY}`,
			'src/reports/table.generated.tsx': `/**\n * This file is auto-generated. Do not edit.\n */\n${STYLE_ONLY}`,
			'tools/client.gen.ts': `${HEADER}${STYLE_ONLY}`,
		}
		expect(await check(files)).toEqual([])
	})

	test('the same source is refused under another name, without the header, or with the header below the first line', async () => {
		const files = {
			'src/reports/view.ts': `${HEADER}${STYLE_ONLY}`,
			'src/reports/plain.gen.ts': STYLE_ONLY,
			'src/reports/late.gen.ts': `\n${HEADER}${STYLE_ONLY}`,
		}
		const expected = (file: string, line: number): string[] => [
			`${file}:${line}:1 suppression-comment`,
			`${file}:${line + 1}:23 type-assertion`,
			`${file}:${line + 2}:21 any-type`,
			`${file}:${line + 3}:47 data-access-location`,
		]
		expect(described(await check(files))).toEqual([
			...expected('src/reports/late.gen.ts', 3),
			...expected('src/reports/plain.gen.ts', 1),
			...expected('src/reports/view.ts', 2),
		])
	})

	test('every rule about what a generated module does still applies', async () => {
		const files = {
			'src/config.gen.ts': `${HEADER}export const url = process.env.DATABASE_URL\nexport const key = 'px_live'\n`
				+ "import type { Ref } from '@fabrika/app'\nexport type Wide = Ref<string, string>\n",
			'web/client.gen.ts': `${HEADER}import { boot } from '@fabrika/app/implement'\nexport { boot }\n`,
		}
		expect(described(await check(files)).sort()).toEqual([
			'src/config.gen.ts:2:20 env-read',
			'src/config.gen.ts:3:20 key-literal',
			'src/config.gen.ts:5:20 capability-widening',
			'web/client.gen.ts:2:1 forbidden-import',
			'web/client.gen.ts:2:1 spa-server-import',
		])
	})

	test("@buzola/codegen 0.0.28's output passes; under another name only its eslint-disable header is refused", async () => {
		expect(await check({ 'web/buzola.gen.ts': BUZOLA_GEN })).toEqual([])
		expect(described(await check({ 'web/routes.ts': BUZOLA_GEN }))).toEqual(['web/routes.ts:2:1 suppression-comment'])
	})
})
