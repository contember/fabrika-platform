// The credentials and addresses of the per-workspace sandboxes of a `dev` environment. The namespace's sandbox host key
// is the bearer of the Box API; each workspace has its own proxy secret and origin. Values are sealed in the vault and
// opened per call; never logged, never returned over the API.

import type { ProviderApprovedAccess } from '@fabrika/provider-contract'
import { type AccessSnapshot, approvedAccess, parseSnapshot } from '../approval/snapshot'
import type { AppEnvRow, ControlRepositories, DevSandboxRow } from '../db'
import { generateProxySecret, proxySecretPurpose } from '../proxy-secret'
import type { Vault, VaultSecretPurpose } from '../vault'

export interface DevSandboxKeyDeps {
	readonly repositories: Pick<ControlRepositories, 'registry' | 'devSandboxes'>
	/** Absent without `FABRIKA_CONTROL_VAULT_KEY`; then every call here fails. */
	readonly vault?: () => Promise<Vault>
}

/** Why a run of a `dev` environment without a workspace does not deploy where the provider serves workspace sandboxes. */
export const DEV_RUN_NEEDS_WORKSPACE = 'a dev environment deploys per workspace through bind_dev'

export const DEV_SANDBOX_VAULT_REQUIRED = "a dev sandbox needs Control's vault, and this installation has none (it needs FABRIKA_CONTROL_VAULT_KEY)"

export function requireVault(deps: Pick<DevSandboxKeyDeps, 'vault'>): Promise<Vault> {
	if (deps.vault === undefined) throw new Error(DEV_SANDBOX_VAULT_REQUIRED)
	return deps.vault()
}

/** The `{ scope, label }` the namespace's sandbox host key is sealed under. */
export function sandboxHostKeyPurpose(namespaceId: string): VaultSecretPurpose {
	return { scope: 'platform', label: `platform:sandbox-host-key:${namespaceId}` }
}

/** 32 random bytes as 64 hex characters: alphanumeric, the only key format the sandbox host accepts. */
export function generateSandboxHostKey(): string {
	return Array.from(crypto.getRandomValues(new Uint8Array(32)), (byte) => byte.toString(16).padStart(2, '0')).join('')
}

/** The namespace's sandbox host API key: generated by the first call, every later call opens the same one. */
export async function sandboxHostKey(deps: DevSandboxKeyDeps, namespaceId: string): Promise<string> {
	const vault = await requireVault(deps)
	const registry = deps.repositories.registry
	const purpose = sandboxHostKeyPurpose(namespaceId)
	const stored = await registry.getNamespaceSandboxKeyRef(namespaceId)
	if (stored !== null) return vault.getSecretForPurpose(stored, purpose)
	const key = generateSandboxHostKey()
	const ref = await vault.putSecret(purpose.scope, purpose.label, key)
	if (await registry.claimNamespaceSandboxKeyRef(namespaceId, ref)) return key
	// Another holder recorded the namespace's key first; it stays the one the sandbox host was given.
	await vault.delete(ref)
	const recorded = await registry.getNamespaceSandboxKeyRef(namespaceId)
	if (recorded === null) throw new Error(`the sandbox host key of namespace ${namespaceId} could not be recorded`)
	return vault.getSecretForPurpose(recorded, purpose)
}

export interface DevSandboxCoordinates {
	readonly appId: string
	readonly env: string
	readonly workspaceId: string
}

/** The `{ scope, label }` a workspace's proxy secret is sealed under: the environment's, narrowed to the workspace. */
export function devSandboxProxySecretPurpose(input: DevSandboxCoordinates): VaultSecretPurpose {
	const purpose = proxySecretPurpose(input.appId, input.env)
	return { scope: purpose.scope, label: `${purpose.label}:${input.workspaceId}` }
}

/**
 * The workspace's proxy secret and its vault reference: the one its sandbox row records, or a newly sealed one, which
 * the caller records with `DevSandboxRepository.markReady` (or deletes with `deleteDevSandboxProxySecret` when it cannot).
 */
export async function devSandboxProxySecret(deps: DevSandboxKeyDeps, input: DevSandboxCoordinates): Promise<{ secret: string; ref: string }> {
	const vault = await requireVault(deps)
	const purpose = devSandboxProxySecretPurpose(input)
	const row = await deps.repositories.devSandboxes.get(input.workspaceId)
	if (row !== null && (row.app_id !== input.appId || row.env !== input.env)) {
		throw new Error(`workspace ${input.workspaceId} has a sandbox in another environment`)
	}
	if (row?.proxy_secret_ref !== null && row?.proxy_secret_ref !== undefined) {
		return { secret: await vault.getSecretForPurpose(row.proxy_secret_ref, purpose), ref: row.proxy_secret_ref }
	}
	const secret = generateProxySecret()
	return { secret, ref: await vault.putSecret(purpose.scope, purpose.label, secret) }
}

/** The proxy secret a sandbox row records; throws when it records none. */
export async function openDevSandboxProxySecret(vault: Vault, row: DevSandboxRow): Promise<string> {
	if (row.proxy_secret_ref === null) throw new Error(`the sandbox of workspace ${row.workspace_id} has no proxy secret`)
	return vault.getSecretForPurpose(
		row.proxy_secret_ref,
		devSandboxProxySecretPurpose({ appId: row.app_id, env: row.env, workspaceId: row.workspace_id }),
	)
}

/** Delete a workspace's sealed proxy secret; a null reference deletes nothing. */
export async function deleteDevSandboxProxySecret(deps: Pick<DevSandboxKeyDeps, 'vault'>, ref: string | null): Promise<void> {
	if (ref === null) return
	await (await requireVault(deps)).delete(ref)
}

/** Where workspace W of a dev environment is served: `https://<W>.<domain>`; the domain is the wildcard base. */
export function devSandboxOrigin(appEnv: Pick<AppEnvRow, 'app_id' | 'env' | 'domain'>, workspaceId: string): string {
	if (appEnv.domain === null || appEnv.domain === '') throw new Error(`dev environment ${appEnv.app_id}/${appEnv.env} has no domain`)
	return `https://${workspaceId}.${appEnv.domain}`
}

/** The host the namespace proxy answers workspace W on. */
export function devSandboxHost(domain: string, workspaceId: string): string {
	return `${workspaceId}.${domain}`
}

/**
 * The snapshot the workspace's proxy table follows: its own published bootstrap run's; null before one published, or when
 * the recorded run is not a bootstrap of this workspace in this environment.
 */
export async function workspacePublication(
	repositories: Pick<ControlRepositories, 'runs'>,
	row: Pick<DevSandboxRow, 'workspace_id' | 'app_id' | 'env' | 'published_run_id'>,
): Promise<{ readonly runId: string; readonly snapshot: AccessSnapshot; readonly access: ProviderApprovedAccess } | null> {
	if (row.published_run_id === null) return null
	const run = await repositories.runs.getRun(row.published_run_id)
	if (run === null || run.snapshot_json === null) return null
	if (run.app_id !== row.app_id || run.env !== row.env || run.lane !== row.workspace_id) return null
	const snapshot = parseSnapshot(run.snapshot_json)
	const access = approvedAccess(snapshot)
	return access === undefined ? null : { runId: run.id, snapshot, access }
}
