import { existsSync, readdirSync, readFileSync, statSync } from 'fs'
import { join } from 'path'
import { GATE_APPROVE, GATE_CHANGES, GATE_VERDICT_ID } from '../../shared/gate'
import { literal } from './build-review'
import { extractFrontMatter, list, scalar } from './frontmatter'
import { readSkeletons } from './skeletons'

export const FLOWS_DIR = '.fabrika/architecture/flows'
export const FLOWS_REVIEW_PATH = '.fabrika/architecture/flows-review.jsx'

export interface Flow {
	slug: string
	/** Repository-relative. */
	path: string
	actor: string
	goal: string
	/** The screen the flow starts on; null when the front matter names none or an invalid one. */
	route: string | null
	/** The screens the flow moves to, valid routes only. */
	leadsTo: string[]
	/** What the reviewer must fix before the map can be trusted. */
	problems: string[]
}

// A route is a path: segments of URL-safe characters, `:name` parameters included. Anything else stays off the map.
const ROUTE = /^\/(?:[A-Za-z0-9._~:-]+(?:\/[A-Za-z0-9._~:-]+)*\/?)?$/
const SLUG = /^[a-z0-9][a-z0-9-]*$/

export function readFlows(repoRoot: string): Flow[] {
	const dir = join(repoRoot, FLOWS_DIR)
	if (!existsSync(dir) || !statSync(dir).isDirectory()) return []
	const flows: Flow[] = []
	for (const entry of readdirSync(dir).sort()) {
		if (!entry.endsWith('.flow.md')) continue
		const file = join(dir, entry)
		if (!statSync(file).isFile() || statSync(file).size === 0) continue
		flows.push(parseFlow(entry.slice(0, -'.flow.md'.length), readFileSync(file, 'utf8')))
	}
	return flows
}

export function parseFlow(slug: string, raw: string): Flow {
	const fm = extractFrontMatter(raw).body
	const problems: string[] = []
	if (!SLUG.test(slug)) problems.push('rename the file to lowercase letters, digits and dashes')
	const rawRoute = scalar(fm['route'])
	let route: string | null = null
	if (rawRoute === undefined || rawRoute === '') problems.push('no `route:` in its front matter')
	else if (!ROUTE.test(rawRoute)) problems.push(`\`route: ${rawRoute}\` is not a path`)
	else route = rawRoute
	const leadsTo: string[] = []
	for (const target of list(fm['leads_to'])) {
		if (ROUTE.test(target)) leadsTo.push(target)
		else problems.push(`\`leads_to\` entry \`${target}\` is not a path`)
	}
	return {
		slug,
		path: `${FLOWS_DIR}/${slug}.flow.md`,
		actor: scalar(fm['actor']) ?? '',
		goal: scalar(fm['goal']) ?? '',
		route,
		leadsTo,
		problems,
	}
}

/** Every screen on the map: each flow's start and every screen a flow leads to. */
export function mappedRoutes(flows: readonly Flow[]): Set<string> {
	return new Set(flows.flatMap((flow) => [...(flow.route ? [flow.route] : []), ...flow.leadsTo]))
}

/** The skeleton URLs no flow puts on the map; a skeleton without a URL is not checked. */
export function unmappedUrls(flows: readonly Flow[], urls: readonly string[]): string[] {
	const routes = mappedRoutes(flows)
	return [...new Set(urls)].filter((url) => !routes.has(url.split(/[?#]/)[0] ?? url)).sort()
}

/** The route check `next` and `advance` report from the skeletons phase on: the issues are induced from these urls. */
export function skeletonRouteWarnings(repoRoot: string): string[] {
	const urls = readSkeletons(join(repoRoot, 'tests', 'browser')).flatMap((skeleton) => (skeleton.url ? [skeleton.url] : []))
	return unmappedUrls(readFlows(repoRoot), urls).map((url) => `skeleton url ${url} is on no flow's route map (route or leads_to)`)
}

export function routeMapMermaid(flows: readonly Flow[]): string {
	const ids = new Map<string, string>()
	const id = (route: string): string => {
		let found = ids.get(route)
		if (found === undefined) {
			found = `s${ids.size}`
			ids.set(route, found)
		}
		return found
	}
	const edges: string[] = []
	for (const flow of flows) {
		if (!flow.route || !SLUG.test(flow.slug)) continue
		const from = id(flow.route)
		for (const target of flow.leadsTo) edges.push(`  ${from} -->|${flow.slug}| ${id(target)}`)
	}
	for (const route of mappedRoutes(flows)) id(route)
	// Routes and slugs were validated above, so neither can close a label.
	const nodes = [...ids].map(([route, nodeId]) => `  ${nodeId}["${route}"]`)
	return ['flowchart LR', ...nodes, ...edges].join('\n')
}

/** The flows gate's view, generated from the flow files so the map is the one they declare. */
export function renderFlowsReview(flows: readonly Flow[], now: Date): string {
	const screens = mappedRoutes(flows).size
	const problems = flows.flatMap((flow) => flow.problems.map((problem) => [flow.path, problem]))
	const lines = [
		`<Section title={${literal(`Flows review — ${flows.length} flows, ${screens} screens`)}}>`,
		`\t<Note>{${
			literal(
				`Generated by \`fabrika builder flows review\` at ${now.toISOString()} from ${FLOWS_DIR}/*.flow.md: each arrow is a flow's \`leads_to\`, labelled with the flow.`,
			)
		}}</Note>`,
	]
	if (screens > 0) lines.push(`\t<Mermaid>{${literal(routeMapMermaid(flows))}}</Mermaid>`)
	lines.push(
		`\t<Table headers={${literal(['Flow', 'Actor', 'Goal', 'Starts at', 'Leads to'])}} rows={${
			literal(flows.map((flow) => [flow.slug, flow.actor, flow.goal, flow.route ?? '(none)', flow.leadsTo.join(', ') || '(none)']))
		}} />`,
	)
	if (problems.length > 0) lines.push(`\t<Table headers={${literal(['Flow file', 'Problem'])}} rows={${literal(problems)}} />`)
	for (const flow of flows) {
		if (!SLUG.test(flow.slug)) continue
		lines.push(
			`\t<Item id={${literal(`flow-${flow.slug}`)}} label={${literal(`${flow.slug} — ${flow.route ?? 'no route'}`)}} badge="flow" badgeVariant="info">`,
			`\t\t<Markdown file="${flow.path}" />`,
			'\t</Item>',
		)
	}
	lines.push(
		`\t<UserInput id="flows-note" label="A missing screen, a wrong transition, or a missing step?" placeholder="write here…" multiline />`,
		`\t<Choice id="${GATE_VERDICT_ID}" label="Verdict" required options={['${GATE_APPROVE}', '${GATE_CHANGES}']} />`,
		'</Section>',
	)
	return lines.join('\n') + '\n'
}
