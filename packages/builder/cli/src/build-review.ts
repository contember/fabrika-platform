import { GATE_APPROVE, GATE_CHANGES, GATE_VERDICT_ID } from '../../shared/gate'
import type { BuildBoard, BuildEvidence } from './build-status'
import type { Issue } from './issues'

export const BUILD_REVIEW_PATH = '.fabrika/build/review.jsx'

/**
 * The build gate's view, generated from the recorded checks so the reviewer sees what ran, not what an agent reported.
 * Every value from the repository reaches the view as a JSON string literal, never as JSX text.
 */
export function renderBuildReview(issues: Issue[], board: BuildBoard, now: Date): string {
	const rows = issues.map((issue) => {
		const rec = board[issue.id]
		const status = rec?.status === 'done' ? 'done' : rec?.status === 'blocked' ? 'blocked' : 'not built'
		return [issue.id, issue.goal, status, rec?.evidence ? describeEvidence(rec.evidence) : 'no recorded check']
	})
	const blocked = issues.flatMap((issue) => {
		const rec = board[issue.id]
		return rec?.status === 'blocked' ? [[issue.id, rec.reason ?? '(no reason given)']] : []
	})
	const done = rows.filter((row) => row[2] === 'done').length

	const lines = [
		`<Section title={${literal(`Build review — ${done}/${issues.length} issues done`)}}>`,
		`\t<Note>{${literal(note(now))}}</Note>`,
		`\t<Table headers={${JSON.stringify(['Issue', 'Goal', 'Status', 'Check'])}} rows={${JSON.stringify(rows)}} />`,
	]
	if (blocked.length > 0) {
		lines.push(`\t<Table headers={${JSON.stringify(['Blocked issue', 'Reason'])}} rows={${JSON.stringify(blocked)}} />`)
	}
	lines.push(
		`\t<UserInput id="build-note" label="Notes for the blocked or unchecked issues?" placeholder="write here…" multiline />`,
		`\t<Choice id="${GATE_VERDICT_ID}" label="Verdict" required options={['${GATE_APPROVE}', '${GATE_CHANGES}']} />`,
		'</Section>',
	)
	return lines.join('\n') + '\n'
}

export function describeEvidence(evidence: BuildEvidence): string {
	const commit = evidence.commit === null ? 'outside git' : `at ${evidence.commit.slice(0, 7)}${evidence.dirty ? ' with uncommitted changes' : ''}`
	return `${evidence.command} · exit ${evidence.exitCode} · ${(evidence.durationMs / 1000).toFixed(1)} s · ${commit} · ${evidence.at}`
}

function note(now: Date): string {
	return `Generated by \`fabrika builder build review\` at ${now.toISOString()} from .fabrika/build/status.json. The builder ran each check itself; "uncommitted changes" means the commit alone does not reproduce the run.`
}

function literal(text: string): string {
	return JSON.stringify(text)
}
