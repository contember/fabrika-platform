import { type SqlDatabase, uuidv7 } from '@fabrika/platform'

import { unixNow } from './sql'

export interface AuditEventRow {
	id: string
	request_id: string
	principal_id: string | null
	principal_label: string
	credential_id: string | null
	app: string
	action: string
	resource_type: string
	resource_id: string | null
	diff: string | null
	metadata: string | null
	created_at: number
}

export interface AuthLogRow {
	/**
	 * THE ONE COLUMN IN THIS SCHEMA WHOSE JS TYPE DEPENDS ON THE BACKEND. `auth_log.id` is engine-
	 * assigned and has no SQLite ∩ Postgres spelling (see the block comment on `auth_log` in
	 * `migrations/0001` and `migrations-postgres/0001`): SQLite's `INTEGER PRIMARY KEY` rowid alias
	 * hands back a `number`; Postgres needs `BIGINT GENERATED BY DEFAULT AS IDENTITY`, and Bun decodes
	 * `int8` as a STRING by column type OID — `'42'`, never `42`, even for small values.
	 *
	 * Narrowing this to `number` would be a lie on Postgres, and widening the column to `INTEGER` to
	 * make it true would cap the highest-volume table in the schema at 2147483647 rows. So the union
	 * stands and the SINGLE reader (`toAuthLogDto`, admin/audit.ts) normalises it. Anything new
	 * that reads this column must do the same — do not assume arithmetic works on it.
	 */
	id: number | string
	request_id: string
	app: string
	kind: 'authenticate'
	principal_id: string | null
	credential_id: string | null
	decision: 'allow' | 'deny'
	reason: string | null
	created_at: number
}

// Inputs that audit/auth-log writes accept (the Worker stamps ids/timestamps).
export interface AuditEventInput {
	requestId: string
	principalId: string | null
	principalLabel: string
	credentialId?: string | null
	app: string
	action: string
	resourceType: string
	resourceId?: string | null
	diff?: unknown
	metadata?: unknown
}

export interface AuthLogInput {
	requestId: string
	app: string
	kind: 'authenticate'
	principalId: string | null
	credentialId?: string | null
	decision: 'allow' | 'deny'
	reason?: string | null
}

export class AuditRepository {
	constructor(protected readonly db: SqlDatabase) {}

	/** Write a domain audit event. Diff/metadata stored verbatim (JSON-encoded). */
	async writeAuditEvent(input: AuditEventInput): Promise<void> {
		const id = uuidv7()
		await this.db
			.prepare(`INSERT INTO audit_events
				(id, request_id, principal_id, principal_label, credential_id, app, action, resource_type, resource_id, diff, metadata, created_at)
				VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`)
			.bind(
				id,
				input.requestId,
				input.principalId,
				input.principalLabel,
				input.credentialId ?? null,
				input.app,
				input.action,
				input.resourceType,
				input.resourceId ?? null,
				input.diff === undefined ? null : JSON.stringify(input.diff),
				input.metadata === undefined ? null : JSON.stringify(input.metadata),
				unixNow(),
			)
			.run()
	}

	/**
	 * `id` is deliberately omitted — the column is auto-assigned (SQLite rowid alias / Postgres
	 * identity; see the note on `auth_log` in migration 0001). Everything else, `created_at`
	 * included, is bound here.
	 */
	async writeAuthLog(input: AuthLogInput): Promise<void> {
		await this.db
			.prepare(`INSERT INTO auth_log
				(request_id, app, kind, principal_id, credential_id, decision, reason, created_at)
				VALUES (?, ?, ?, ?, ?, ?, ?, ?)`)
			.bind(
				input.requestId,
				input.app,
				input.kind,
				input.principalId,
				input.credentialId ?? null,
				input.decision,
				input.reason ?? null,
				unixNow(),
			)
			.run()
	}

	// ── Audit reads (admin) ───────────────────────────────────────────────────

	async listAuditEvents(filter: {
		resourceType?: string
		resourceId?: string
		principalId?: string
		action?: string
		requestId?: string
		before?: string
		limit: number
	}): Promise<AuditEventRow[]> {
		const where: string[] = []
		const binds: (string | number)[] = []
		if (filter.resourceType) {
			where.push('resource_type = ?')
			binds.push(filter.resourceType)
		}
		if (filter.resourceId) {
			where.push('resource_id = ?')
			binds.push(filter.resourceId)
		}
		if (filter.principalId) {
			where.push('principal_id = ?')
			binds.push(filter.principalId)
		}
		if (filter.action) {
			where.push('action = ?')
			binds.push(filter.action)
		}
		if (filter.requestId) {
			where.push('request_id = ?')
			binds.push(filter.requestId)
		}
		if (filter.before) {
			// Cursor by UUIDv7 id — keyset pagination, descending. The generator is monotonic (RFC 9562
			// §6.2 counter), so two events from one millisecond cannot tie and the cursor can neither
			// skip nor repeat a row.
			where.push('id < ?')
			binds.push(filter.before)
		}
		const sql = `SELECT * FROM audit_events${where.length ? ` WHERE ${where.join(' AND ')}` : ''} ORDER BY id DESC LIMIT ?`
		binds.push(filter.limit)
		const { results } = await this.db.prepare(sql).bind(...binds).all<AuditEventRow>()
		return results
	}

	async listAuthLog(filter: {
		principalId?: string
		requestId?: string
		decision?: 'allow' | 'deny'
		before?: number
		limit: number
	}): Promise<AuthLogRow[]> {
		const where: string[] = []
		const binds: (string | number)[] = []
		if (filter.principalId) {
			where.push('principal_id = ?')
			binds.push(filter.principalId)
		}
		if (filter.requestId) {
			where.push('request_id = ?')
			binds.push(filter.requestId)
		}
		if (filter.decision) {
			where.push('decision = ?')
			binds.push(filter.decision)
		}
		if (filter.before !== undefined) {
			// Cursor by rowid (time-correlated, monotonic) — keyset pagination.
			where.push('id < ?')
			binds.push(filter.before)
		}
		const sql = `SELECT * FROM auth_log${where.length ? ` WHERE ${where.join(' AND ')}` : ''} ORDER BY id DESC LIMIT ?`
		binds.push(filter.limit)
		const { results } = await this.db.prepare(sql).bind(...binds).all<AuthLogRow>()
		return results
	}

	// ── Retention (cron) ──────────────────────────────────────────────────────

	/**
	 * Prune `auth_log` rows older than `olderThanSeconds` (unix seconds). The rowid
	 * is time-correlated, so pruning by `created_at` needs no extra index.
	 */
	async pruneAuthLog(olderThanSeconds: number): Promise<number> {
		const result = await this.db
			.prepare('DELETE FROM auth_log WHERE created_at < ?')
			.bind(olderThanSeconds)
			.run()
		return result.meta.changes ?? 0
	}
}
