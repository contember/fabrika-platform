import { type SqlDatabase, type SqlQueryResult, type SqlStatement, uuidv7 } from '@fabrika/platform'

import { unixNow } from './sql'

export interface AuditEventRow {
	id: string
	request_id: string
	principal_id: string | null
	principal_label: string
	credential_id: string | null
	app: string
	action: string
	resource_type: string
	resource_id: string | null
	diff: string | null
	metadata: string | null
	created_at: number
}

export interface AuthLogRow {
	/**
	 * THE ONE COLUMN IN THIS SCHEMA WHOSE JS TYPE DEPENDS ON THE BACKEND. `auth_log.id` is engine-
	 * assigned and has no SQLite ∩ Postgres spelling (see the block comment on `auth_log` in
	 * `migrations/0001` and `migrations-postgres/0001`): SQLite's `INTEGER PRIMARY KEY` rowid alias
	 * hands back a `number`; Postgres needs `BIGINT GENERATED BY DEFAULT AS IDENTITY`, and Bun decodes
	 * `int8` as a STRING by column type OID — `'42'`, never `42`, even for small values.
	 *
	 * Narrowing this to `number` would be a lie on Postgres, and widening the column to `INTEGER` to
	 * make it true would cap the highest-volume table in the schema at 2147483647 rows. So the union
	 * stands and the SINGLE reader (`toAuthLogDto`, admin/audit.ts) normalises it. Anything new
	 * that reads this column must do the same — do not assume arithmetic works on it.
	 */
	id: number | string
	request_id: string
	app: string
	kind: AuthLogKind
	principal_id: string | null
	credential_id: string | null
	decision: 'allow' | 'deny'
	reason: string | null
	created_at: number
	/** 1 when the session's principal held the installation-admin action at login; 0 otherwise. */
	privileged: number
	/** The terminal of the session this row is about (ADR-0067), copied from the session row. */
	terminal_id: string | null
	/** The application that asserted that session's person on `terminal_id`. */
	asserted_by: string | null
}

/** A login attempt (`authenticate`) or the end of a session (`logout`). */
export type AuthLogKind = 'authenticate' | 'logout'

// Inputs that audit/auth-log writes accept (the Worker stamps ids/timestamps).
export interface AuditEventInput {
	requestId: string
	principalId: string | null
	principalLabel: string
	credentialId?: string | null
	app: string
	action: string
	resourceType: string
	resourceId?: string | null
	diff?: unknown
	metadata?: unknown
}

export interface AuthLogInput {
	requestId: string
	app: string
	kind: AuthLogKind
	principalId: string | null
	credentialId?: string | null
	decision: 'allow' | 'deny'
	reason?: string | null
	/** The principal held the installation-admin action when this session was opened. */
	privileged?: boolean
	/** The session's `terminal_id` and `asserted_by`, read from its row, never from what an application sent. */
	terminal?: { terminalId: string; assertedBy: string } | null
}

/**
 * The `principal_label` an audit row stores for a principal: a user's is its id, because a user's label spells its
 * mailbox and an audit row holds no email; a service's is its key name. A caller of unknown kind is treated as a user.
 */
export function auditLabelOf(
	principal: { readonly id: string; readonly type: 'user' | 'service' | undefined; readonly label: string | null },
): string {
	return principal.type === 'service' ? principal.label ?? principal.id : principal.id
}

/** A write that ends in `RETURNING`, as SQL text and its bound values, so an `AuditWriter` can wrap it. */
export interface SqlChange {
	readonly sql: string
	readonly binds: readonly unknown[]
}

/** The SQL dialect a composition root runs on: D1/SQLite or Postgres. */
export type SqlDialect = 'sqlite' | 'postgres'

const AUDIT_COLUMNS =
	'(id, request_id, principal_id, principal_label, credential_id, app, action, resource_type, resource_id, diff, metadata, created_at)'

/** The bound values of one audit row, in `AUDIT_COLUMNS` order; `id` is the row's own. */
function auditValues(id: string, event: AuditEventInput): unknown[] {
	return [
		id,
		event.requestId,
		event.principalId,
		event.principalLabel,
		event.credentialId ?? null,
		event.app,
		event.action,
		event.resourceType,
		event.resourceId ?? null,
		event.diff === undefined ? null : JSON.stringify(event.diff),
		event.metadata === undefined ? null : JSON.stringify(event.metadata),
		unixNow(),
	]
}

const AUDIT_PLACEHOLDERS = '?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?'

/**
 * The INSERT of one audit row, for the batch of an unconditional change it records: the row and the change commit
 * together, and a failed insert rolls the change back. Diff and metadata are stored JSON-encoded.
 */
export function auditEventStatement(db: SqlDatabase, event: AuditEventInput): SqlStatement {
	return db.prepare(`INSERT INTO audit_events ${AUDIT_COLUMNS} VALUES (${AUDIT_PLACEHOLDERS})`).bind(...auditValues(uuidv7(), event))
}

/**
 * `auditEventStatement` whose `resource_id` is read in the batch by `resourceId`, a one-row SELECT of one column: for
 * a resource whose id the batch itself settles, such as a principal another writer may have created first.
 */
export function auditEventAboutStatement(db: SqlDatabase, event: AuditEventInput, resourceId: SqlChange): SqlStatement {
	const values = auditValues(uuidv7(), event)
	const before = values.slice(0, 8)
	const after = values.slice(9)
	return db
		.prepare(`INSERT INTO audit_events ${AUDIT_COLUMNS} SELECT ?, ?, ?, ?, ?, ?, ?, ?, (${resourceId.sql}), ?, ?, ?`)
		.bind(...before, ...resourceId.binds, ...after)
}

/** A change and its record, as batch statements, and where the change's `RETURNING` rows land in the batch results. */
export interface AuditedChange {
	readonly statements: SqlStatement[]
	/** The rows the LAST change returned, read from the results of a batch whose statements start at `offset`. */
	rows<T>(results: SqlQueryResult<T>[], offset?: number): T[]
}

/**
 * Writes the record of a guarded change exactly when the change changed a row, decided by the change itself and never
 * by an earlier existence check another writer can invalidate.
 *
 * - **Postgres** runs the changes and the record as ONE statement: `WITH c0 AS (<change> RETURNING …), … INSERT INTO
 *   audit_events … WHERE EXISTS (SELECT 1 FROM c0) …`. The record sees exactly the rows this statement changed.
 *   Data-modifying CTEs share one snapshot, so the changes of one group must not depend on each other.
 * - **SQLite/D1** has no data-modifying CTE, but it serializes writers, so `changes()` right after each change is
 *   exact: the record is inserted after the first change that changed a row, and its fixed id keeps it to one.
 */
export class AuditWriter {
	constructor(
		private readonly db: SqlDatabase,
		readonly dialect: SqlDialect,
	) {}

	/** The changes and, when `event` is given, their record; without one, the changes alone (a seed, a test). */
	changed(changes: readonly SqlChange[], event: AuditEventInput | undefined): AuditedChange {
		if (changes.length === 0) {
			throw new Error('an audited change needs at least one write')
		}
		if (event === undefined) {
			const last = changes.length - 1
			return {
				statements: changes.map((change) => this.db.prepare(change.sql).bind(...change.binds)),
				rows: (results, offset = 0) => results[offset + last]?.results ?? [],
			}
		}
		const id = uuidv7()
		const values = auditValues(id, event)
		if (this.dialect === 'postgres') {
			const ctes = changes.map((change, index) => `c${index} AS (${change.sql})`)
			const changed = changes.map((_, index) => `EXISTS (SELECT 1 FROM c${index})`).join(' OR ')
			const statement = this.db
				.prepare(`WITH ${ctes.join(', ')}, recorded AS (
					INSERT INTO audit_events ${AUDIT_COLUMNS} SELECT ${AUDIT_PLACEHOLDERS} WHERE ${changed} RETURNING id
				) SELECT * FROM c${changes.length - 1}`)
				.bind(...changes.flatMap((change) => change.binds), ...values)
			return { statements: [statement], rows: (results, offset = 0) => results[offset]?.results ?? [] }
		}
		const statements = changes.flatMap((change) => [
			this.db.prepare(change.sql).bind(...change.binds),
			this.db
				.prepare(`INSERT INTO audit_events ${AUDIT_COLUMNS} SELECT ${AUDIT_PLACEHOLDERS}
					WHERE changes() > 0 AND NOT EXISTS (SELECT 1 FROM audit_events WHERE id = ?)`)
				.bind(...values, id),
		])
		const last = (changes.length - 1) * 2
		return { statements, rows: (results, offset = 0) => results[offset + last]?.results ?? [] }
	}

	/** Run one audited group as its own batch and answer the rows its last change returned. */
	async run<T>(changes: readonly SqlChange[], event: AuditEventInput | undefined): Promise<T[]> {
		const change = this.changed(changes, event)
		const [only, ...more] = change.statements
		// One statement is atomic alone, and a Postgres transaction would hold a pooled connection for nothing.
		if (only !== undefined && more.length === 0) {
			return change.rows([await only.all<T>()])
		}
		return change.rows(await this.db.batch<T>(change.statements))
	}
}

/**
 * The INSERT of one `auth_log` row. `id` is deliberately omitted — the column is auto-assigned (SQLite rowid alias /
 * Postgres identity; see the note on `auth_log` in migration 0001). Everything else, `created_at` included, is bound.
 */
export function authLogStatement(db: SqlDatabase, input: AuthLogInput): SqlStatement {
	return db
		.prepare(`INSERT INTO auth_log
			(request_id, app, kind, principal_id, credential_id, decision, reason, privileged, created_at, terminal_id, asserted_by)
			VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`)
		.bind(
			input.requestId,
			input.app,
			input.kind,
			input.principalId,
			input.credentialId ?? null,
			input.decision,
			input.reason ?? null,
			input.privileged === true ? 1 : 0,
			unixNow(),
			input.terminal?.terminalId ?? null,
			input.terminal?.assertedBy ?? null,
		)
}

export class AuditRepository {
	constructor(
		protected readonly db: SqlDatabase,
		readonly writer: AuditWriter = new AuditWriter(db, 'sqlite'),
	) {}

	/** Write an audit row that records no change of IAM's own, such as an application's event or an admin's access. */
	async writeAuditEvent(input: AuditEventInput): Promise<void> {
		await auditEventStatement(this.db, input).run()
	}

	async writeAuthLog(input: AuthLogInput): Promise<void> {
		await authLogStatement(this.db, input).run()
	}

	/**
	 * Run a change of several repositories and its audit rows as ONE batch, in order. Every statement must come from
	 * the database this repository holds; a composition root builds all repositories over one.
	 */
	commit<T = Record<string, unknown>>(statements: SqlStatement[]): Promise<SqlQueryResult<T>[]> {
		return this.db.batch<T>(statements)
	}

	/** The statement form of `auditEventStatement`, for a use case that composes a `commit`. */
	eventStatement(event: AuditEventInput): SqlStatement {
		return auditEventStatement(this.db, event)
	}

	// ── Audit reads (admin) ───────────────────────────────────────────────────

	async listAuditEvents(filter: {
		resourceType?: string
		resourceId?: string
		principalId?: string
		subjectPrincipalId?: string
		action?: string
		/** Actions to leave out, before the page is cut, so `limit` counts only the rows that remain. */
		excludeActions?: readonly string[]
		requestId?: string
		before?: string
		limit: number
	}): Promise<AuditEventRow[]> {
		const where: string[] = []
		const binds: (string | number)[] = []
		if (filter.subjectPrincipalId) {
			// Old events already identify the affected person in metadata. Guard malformed legacy JSON on both engines.
			const subject = this.writer.dialect === 'postgres'
				? "CASE WHEN metadata IS JSON THEN CAST(metadata AS jsonb) ->> 'principalId' END"
				: "CASE WHEN json_valid(metadata) THEN json_extract(metadata, '$.principalId') END"
			where.push(`((resource_type = 'principal' AND resource_id = ?) OR ${subject} = ?
				OR (action = 'iam.member.accept' AND principal_id = ?)
				OR (resource_type = 'oauth_grant' AND resource_id IN (SELECT id FROM oauth_grants WHERE principal_id = ?)))`)
			binds.push(filter.subjectPrincipalId, filter.subjectPrincipalId, filter.subjectPrincipalId, filter.subjectPrincipalId)
		}
		if (filter.resourceType) {
			where.push('resource_type = ?')
			binds.push(filter.resourceType)
		}
		if (filter.resourceId) {
			where.push('resource_id = ?')
			binds.push(filter.resourceId)
		}
		if (filter.principalId) {
			where.push('principal_id = ?')
			binds.push(filter.principalId)
		}
		if (filter.action) {
			where.push('action = ?')
			binds.push(filter.action)
		}
		if (filter.excludeActions !== undefined && filter.excludeActions.length > 0) {
			where.push(`action NOT IN (${filter.excludeActions.map(() => '?').join(', ')})`)
			binds.push(...filter.excludeActions)
		}
		if (filter.requestId) {
			where.push('request_id = ?')
			binds.push(filter.requestId)
		}
		if (filter.before) {
			// Cursor by UUIDv7 id — keyset pagination, descending. The generator is monotonic (RFC 9562
			// §6.2 counter), so two events from one millisecond cannot tie and the cursor can neither
			// skip nor repeat a row.
			where.push('id < ?')
			binds.push(filter.before)
		}
		const sql = `SELECT * FROM audit_events${where.length ? ` WHERE ${where.join(' AND ')}` : ''} ORDER BY id DESC LIMIT ?`
		binds.push(filter.limit)
		const { results } = await this.db.prepare(sql).bind(...binds).all<AuditEventRow>()
		return results
	}

	async listAuthLog(filter: {
		principalId?: string
		requestId?: string
		decision?: 'allow' | 'deny'
		before?: number
		limit: number
	}): Promise<AuthLogRow[]> {
		const where: string[] = []
		const binds: (string | number)[] = []
		if (filter.principalId) {
			where.push('principal_id = ?')
			binds.push(filter.principalId)
		}
		if (filter.requestId) {
			where.push('request_id = ?')
			binds.push(filter.requestId)
		}
		if (filter.decision) {
			where.push('decision = ?')
			binds.push(filter.decision)
		}
		if (filter.before !== undefined) {
			// Cursor by rowid (time-correlated, monotonic) — keyset pagination.
			where.push('id < ?')
			binds.push(filter.before)
		}
		const sql = `SELECT * FROM auth_log${where.length ? ` WHERE ${where.join(' AND ')}` : ''} ORDER BY id DESC LIMIT ?`
		binds.push(filter.limit)
		const { results } = await this.db.prepare(sql).bind(...binds).all<AuthLogRow>()
		return results
	}

	// ── Retention (cron) ──────────────────────────────────────────────────────

	/**
	 * Prune `auth_log` rows older than `olderThanSeconds` (unix seconds). The rowid
	 * is time-correlated, so pruning by `created_at` needs no extra index.
	 */
	async pruneAuthLog(olderThanSeconds: number): Promise<number> {
		const result = await this.db
			.prepare('DELETE FROM auth_log WHERE created_at < ?')
			.bind(olderThanSeconds)
			.run()
		return result.meta.changes ?? 0
	}

	/** Prune `audit_events` older than `olderThanSeconds` — only where the operator set an audit retention. */
	async pruneAuditEvents(olderThanSeconds: number): Promise<number> {
		const result = await this.db.prepare('DELETE FROM audit_events WHERE created_at < ?').bind(olderThanSeconds).run()
		return result.meta.changes ?? 0
	}
}
