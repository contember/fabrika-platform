const plural = new Intl.PluralRules('uk')

/** "символ" agreeing with `count`: 1 символ, 2 символи, 5 символів (21 символ, 22 символи, 11 символів). */
function characters(count: number): string {
	switch (plural.select(count)) {
		case 'one':
			return 'символ'
		case 'few':
			return 'символи'
		default:
			return 'символів'
	}
}
