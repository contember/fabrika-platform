// `fabrika db codegen` for an application on SQLite: the migrations applied to an in-memory database, read back and
// rendered with the Postgres codegen's renderer.

import { describe, expect, test } from 'bun:test'
import ts from 'typescript'
import { CodegenError } from '../codegen'
import { generateSqliteSchema } from '../codegen-sqlite'
import { SQLITE_FRAMEWORK_MIGRATIONS } from '../migrations-sqlite'
import type { SqliteMigrationBundle } from '../sqlite-migrate'

const framework: SqliteMigrationBundle = { bundle: 'fabrika', migrations: SQLITE_FRAMEWORK_MIGRATIONS }
const app = (...sql: string[]): SqliteMigrationBundle => ({
	bundle: 'app',
	migrations: sql.map((text, index) => ({ name: `2026010100000${index}_step.sql`, sql: text })),
})

const SCHEMA = `CREATE TABLE authors (
	id INTEGER PRIMARY KEY,
	name VARCHAR(80) NOT NULL
);
CREATE TABLE books (
	isbn CHAR(13) NOT NULL,
	edition SMALLINT NOT NULL,
	author_id INTEGER NOT NULL REFERENCES authors,
	PRIMARY KEY (isbn, edition)
);
CREATE TABLE copies (
	id UUID PRIMARY KEY NOT NULL,
	isbn TEXT NOT NULL,
	edition INT NOT NULL,
	shelf BIGINT,
	price REAL,
	weight DOUBLE,
	width FLOAT,
	lent BOOLEAN NOT NULL DEFAULT 0,
	acquired_at TIMESTAMPTZ NOT NULL,
	checked_at TIMESTAMP,
	scanned_at DATETIME,
	printed_on DATE,
	cover BLOB,
	label TEXT GENERATED ALWAYS AS (isbn || '-' || edition),
	FOREIGN KEY (isbn, edition) REFERENCES books (isbn, edition)
);`

const interfaceOf = (source: string, name: string): string => {
	const start = source.indexOf(`export interface ${name} {`)
	return source.slice(start, source.indexOf('}\n', start) + 2)
}

const entryOf = (source: string, table: string): string => {
	const start = source.indexOf(`\t'${table}': {`)
	return source.slice(start, source.indexOf('\n\t},\n', start) + 5)
}

describe('generateSqliteSchema', () => {
	test('maps every declared type, nullability, defaults, generated columns and foreign keys', async () => {
		const { source } = await generateSqliteSchema([framework, app(SCHEMA)])
		expect(source.startsWith('// @generated by fabrika db codegen')).toBe(true)
		expect(source).toContain("import type { TypedColumnList } from '@fabrika/db'\n")
		expect(source).toContain("import type { ColumnType, Generated, GeneratedAlways } from 'kysely'\n")
		expect(interfaceOf(source, 'AuthorsTable')).toBe('export interface AuthorsTable {\n\tid: Generated<number>\n\tname: string\n}\n')
		expect(interfaceOf(source, 'BooksTable')).toBe('export interface BooksTable {\n\tisbn: string\n\tedition: number\n\tauthor_id: number\n}\n')
		expect(interfaceOf(source, 'CopiesTable')).toBe(
			[
				'export interface CopiesTable {',
				'\tid: string',
				'\tisbn: string',
				'\tedition: number',
				'\tshelf: number | null',
				'\tprice: number | null',
				'\tweight: number | null',
				'\twidth: number | null',
				'\tlent: Generated<boolean>',
				'\tacquired_at: ColumnType<Date, Date | string, Date | string>',
				'\tchecked_at: ColumnType<Date | null, Date | string | null, Date | string | null>',
				'\tscanned_at: ColumnType<Date | null, Date | string | null, Date | string | null>',
				'\tprinted_on: string | null',
				'\tcover: Uint8Array | null',
				'\tlabel: GeneratedAlways<string | null>',
				'}\n',
			].join('\n'),
		)
		expect(source).toContain('export interface DB {\n\tauthors: AuthorsTable\n\tbooks: BooksTable\n\tcopies: CopiesTable\n}\n')
		expect(entryOf(source, 'books')).toContain(
			"\t\tforeignKeys: [\n\t\t\t{\n\t\t\t\tcolumns: ['author_id'],\n\t\t\t\ttable: 'authors',\n\t\t\t\treferences: ['id'],\n\t\t\t},\n\t\t],\n",
		)
		const copies = entryOf(source, 'copies')
		expect(copies).toContain(
			"\t\tforeignKeys: [\n\t\t\t{\n\t\t\t\tcolumns: ['isbn', 'edition'],\n\t\t\t\ttable: 'books',\n\t\t\t\treferences: ['isbn', 'edition'],\n\t\t\t},\n\t\t],\n",
		)
		expect(copies).toContain("\t\tdates: ['printed_on'],\n\t\ttimestamps: ['acquired_at', 'checked_at', 'scanned_at'],\n\t\tbooleans: ['lent'],\n")
		expect(entryOf(source, 'authors')).toBe("\t'authors': {\n\t\tcolumns: [\n\t\t\t'id',\n\t\t\t'name',\n\t\t],\n\t\tforeignKeys: [],\n\t},\n")
	})

	test('types a column declared JSONB as Postgres types jsonb, and refuses JSON naming JSONB', async () => {
		const { source } = await generateSqliteSchema([
			app('CREATE TABLE links (id TEXT PRIMARY KEY NOT NULL, metadata JSONB NOT NULL, extra jsonb);'),
		])
		expect(source).toContain("import type { JsonColumnValue, TypedColumnList } from '@fabrika/db'\n")
		expect(interfaceOf(source, 'LinksTable')).toBe(
			[
				'export interface LinksTable {',
				'\tid: string',
				'\tmetadata: ColumnType<unknown, JsonColumnValue, JsonColumnValue>',
				'\textra: ColumnType<unknown | null, JsonColumnValue | null, JsonColumnValue | null>',
				'}\n',
			].join('\n'),
		)
		expect(entryOf(source, 'links')).toContain("\t\tforeignKeys: [],\n\t\tjson: ['metadata', 'extra'],\n")
		await expect(generateSqliteSchema([app('CREATE TABLE links (id TEXT PRIMARY KEY, metadata JSON);')])).rejects.toThrow(
			"links.metadata has declared type 'JSON'; declare it JSONB",
		)
	})

	test("leaves out the framework tables, the ledger and SQLite's own", async () => {
		const { source } = await generateSqliteSchema([framework, app('CREATE TABLE notes (id INTEGER PRIMARY KEY AUTOINCREMENT, body TEXT);')])
		expect(source).not.toContain('fabrika_')
		expect(source).not.toContain('sqlite_')
		expect(source).toContain('export interface DB {\n\tnotes: NotesTable\n}\n')
	})

	test('runs every statement of a migration whose first statement adds a column with a CHECK', async () => {
		// bun:sqlite reports one result column for this ALTER TABLE, which once sent the text down the read path and ran
		// only its first statement.
		const { source } = await generateSqliteSchema([
			app(
				'CREATE TABLE notes (id INTEGER PRIMARY KEY);',
				"ALTER TABLE notes ADD COLUMN state TEXT NOT NULL DEFAULT 'draft' CHECK (state IN ('draft', 'sent'));\nALTER TABLE notes ADD COLUMN sent_at TIMESTAMP;\nCREATE TABLE tags (id INTEGER PRIMARY KEY);",
			),
		])
		expect(interfaceOf(source, 'NotesTable')).toContain('\tsent_at: ')
		expect(source).toContain('export interface TagsTable {')
	})

	test('the generated module compiles', async () => {
		const { source } = await generateSqliteSchema([framework, app(SCHEMA)])
		const { diagnostics } = ts.transpileModule(source, { reportDiagnostics: true, compilerOptions: { module: ts.ModuleKind.ESNext } })
		expect(diagnostics ?? []).toEqual([])
	})

	test('refuses a declared type the data layer does not read, naming the table, the column and the type', async () => {
		for (const declared of ['NUMERIC', 'JSON', 'ANY']) {
			const error = await generateSqliteSchema([app(`CREATE TABLE things (id TEXT PRIMARY KEY, meta ${declared});`)]).then(
				() => undefined,
				(rejected: unknown) => rejected,
			)
			expect(error).toBeInstanceOf(CodegenError)
			expect(String(error)).toContain(`things.meta has declared type '${declared}'`)
		}
		const untyped = await generateSqliteSchema([app('CREATE TABLE things (id TEXT PRIMARY KEY, meta);')]).then(
			() => undefined,
			(rejected: unknown) => rejected,
		)
		expect(untyped).toBeInstanceOf(CodegenError)
	})

	test('leaves out a generated column of a declared type it does not read, naming it; one with no declared type is refused', async () => {
		const module = await generateSqliteSchema([
			app(`CREATE TABLE things (
				id TEXT PRIMARY KEY NOT NULL,
				body TEXT NOT NULL,
				meta JSON GENERATED ALWAYS AS (json_object('body', body)) VIRTUAL
			);`),
		])
		expect(module.leftOut).toEqual([{ table: 'things', column: 'meta', type: 'JSON', of: 'generated' }])
		expect(interfaceOf(module.source, 'ThingsTable')).toBe(
			'export interface ThingsTable {\n\tid: string\n\tbody: string\n\t// meta (JSON, generated) is left out: the data layer does not read it; ctx.sql does\n}\n',
		)
		expect(entryOf(module.source, 'things')).toBe("\t'things': {\n\t\tcolumns: [\n\t\t\t'id',\n\t\t\t'body',\n\t\t],\n\t\tforeignKeys: [],\n\t},\n")
		const untyped = await generateSqliteSchema([
			app('CREATE TABLE things (id TEXT PRIMARY KEY NOT NULL, body TEXT NOT NULL, size GENERATED ALWAYS AS (length(body)) STORED);'),
		]).then(() => undefined, (rejected: unknown) => rejected)
		expect(untyped).toBeInstanceOf(CodegenError)
		expect(String(untyped)).toContain("things.size has declared type '', which the data layer does not read or bind on SQLite")
		expect(String(untyped)).toContain('; declare the type of the generated column')
		const unique = await generateSqliteSchema([
			app(`CREATE TABLE things (id TEXT PRIMARY KEY NOT NULL, body TEXT NOT NULL, meta JSON GENERATED ALWAYS AS (json_object('body', body)) VIRTUAL);
				CREATE UNIQUE INDEX things_meta ON things (meta);`),
		]).then(() => undefined, (rejected: unknown) => rejected)
		expect(String(unique)).toContain(
			'things.meta is a generated column of a type the data layer does not read, so codegen leaves it out, but it is in the primary key or a unique key',
		)
	})
})

describe('generateSqliteSchema of a view', () => {
	const VIEWS = `CREATE TABLE deals (id TEXT PRIMARY KEY NOT NULL, org_id TEXT NOT NULL, title TEXT NOT NULL, opened_at TIMESTAMPTZ NOT NULL);
CREATE TABLE activities (id TEXT PRIMARY KEY NOT NULL, deal_id TEXT NOT NULL REFERENCES deals, at TIMESTAMPTZ NOT NULL);
CREATE VIEW deal_summaries AS
	SELECT d.id AS deal_id, d.org_id, d.title, d.opened_at, CAST(count(a.id) AS INTEGER) AS activities, max(a.at) AS last_at,
		CAST(sum(1.5) AS REAL) AS score, CAST(d.title AS TEXT) AS label
	FROM deals d LEFT JOIN activities a ON a.deal_id = d.id GROUP BY d.id;
CREATE VIEW untyped AS SELECT 1 + 1 AS two;`

	test('types each column by the table column it selects or its cast, nullable, and marks the entry a view', async () => {
		const module = await generateSqliteSchema([framework, app(VIEWS)])
		expect(interfaceOf(module.source, 'DealSummariesView')).toBe(
			[
				'export interface DealSummariesView {',
				'\tdeal_id: string | null',
				'\torg_id: string | null',
				'\ttitle: string | null',
				'\topened_at: ColumnType<Date | null, Date | string | null, Date | string | null>',
				'\tactivities: number | null',
				'\t// last_at (no declared type, of a view) is left out: the data layer does not read it; cast it to a type it reads, or read it with ctx.sql',
				'\tscore: number | null',
				'\tlabel: string | null',
				'}',
				'',
			].join('\n'),
		)
		const entry = entryOf(module.source, 'deal_summaries')
		expect(entry).toContain('\t\tforeignKeys: [],\n')
		expect(entry).toContain("\t\ttimestamps: ['opened_at'],\n")
		expect(entry).toContain('\t\tview: true,\n')
		expect(entryOf(module.source, 'deals')).not.toContain('view')
		expect(module.source).toContain("\n\tdeals: DealsTable\n}\n\nexport type Views = 'deal_summaries'\n\nexport const columns")
		expect(module.source).toContain('export const columns: TypedColumnList<DB, Views> = {')
	})

	test('names every left-out view column, and leaves out a view with no column it reads', async () => {
		const module = await generateSqliteSchema([framework, app(VIEWS)])
		expect(module.leftOut).toEqual([
			{ table: 'deal_summaries', column: 'last_at', type: '', of: 'view' },
			{ table: 'untyped', column: 'two', type: '', of: 'view' },
		])
		expect(module.source).not.toContain('UntypedView')
		expect(module.source).not.toContain("'untyped'")
	})

	test('a schema without a view keeps the plain column list type', async () => {
		const { source } = await generateSqliteSchema([framework, app(SCHEMA)])
		expect(source).toContain('export const columns: TypedColumnList<DB> = {')
	})
})
