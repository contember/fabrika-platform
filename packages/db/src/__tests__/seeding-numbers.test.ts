// The numbers the isolation fixture writes: `1` into a number column no unique index covers, so a bounded CHECK and a
// small numeric pass; into one a unique index covers, the next number above the largest of the row's group (the index's
// other columns as the row has them, the whole column for a one-column index), rows the migration wrote included. Only
// an index of plain key columns with no predicate counts: a partial index, one on an expression and an INCLUDE column
// are left alone. A type with no next number, and a value another row holds where the seed writes it, are seed limits
// naming the index. On SQLite always, on Postgres when FABRIKA_TEST_POSTGRES_URL is set (it skips cleanly otherwise).

import { afterAll, describe, expect, test } from 'bun:test'
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { defineTables } from '../policy'
import { testDatabase as postgresDatabase } from '../testing'
import { SeedLimitError } from '../testing-shared'
import { testDatabase as sqliteDatabase } from '../testing-sqlite'
import type { TypedColumnList } from '../vocabulary-tables'

interface DB {
	entries: {
		id: string
		ledger_id: string
		number: number
		rank: number
		code: string
		slot: number
		tally: number
		rating: number
		weight: string
		label: string
	}
	stamps: { id: string; serial: number }
	scores: { id: string; score: number }
	badges: { id: string; flag: string }
	tickets: { id: string; seq: number }
	shelves: { id: string; bay: number | null; n: number }
}

const columns: TypedColumnList<DB> = {
	entries: { columns: ['id', 'ledger_id', 'number', 'rank', 'code', 'slot', 'tally', 'rating', 'weight', 'label'], foreignKeys: [] },
	stamps: { columns: ['id', 'serial'], foreignKeys: [] },
	scores: { columns: ['id', 'score'], foreignKeys: [] },
	badges: { columns: ['id', 'flag'], foreignKeys: [] },
	tickets: { columns: ['id', 'seq'], foreignKeys: [] },
	shelves: { columns: ['id', 'bay', 'n'], foreignKeys: [] },
}
const vocabulary = {
	dimensions: { ledger: {}, entry: { in: 'ledger' }, stamp: {}, score: {}, badge: {}, ticket: {}, shelf: {} },
	actions: { 'entries.read': 'Read entries', 'entries.write': 'Write entries' },
} as const

const tables = defineTables(vocabulary, columns)({
	entries: {
		scope: { dimension: 'entry', key: 'id', in: { dimension: 'ledger', column: 'ledger_id' } },
		actions: { read: 'entries.read', insert: 'entries.write', update: 'entries.write' },
		insert: ['number', 'rank', 'code', 'slot', 'tally', 'rating', 'weight', 'label'],
		update: ['number', 'rank', 'code', 'slot', 'tally', 'rating', 'weight'],
	},
	stamps: { scope: { dimension: 'stamp', key: 'id' }, actions: { read: 'entries.read' } },
	scores: { scope: { dimension: 'score', key: 'id' }, actions: { read: 'entries.read' } },
	badges: { scope: { dimension: 'badge', key: 'id' }, actions: { read: 'entries.read' } },
	tickets: { scope: { dimension: 'ticket', key: 'id' }, actions: { read: 'entries.read', update: 'entries.write' }, update: ['seq'] },
	shelves: { scope: { dimension: 'shelf', key: 'id' }, actions: { read: 'entries.read', update: 'entries.write' }, update: ['n'] },
})

/**
 * The same schema in each dialect (SQLite has no INCLUDE, no NUMERIC, no Infinity literal, no identity and no NULLS NOT
 * DISTINCT: tickets and shelves are Postgres's only), with rows the migration writes: an entry numbered 7 in its own
 * ledger, with the code 41, the slot 5 and the tally 5; a stamp whose serial is the largest its type holds; a score of
 * Infinity; a badge with the first flag its CHECK lists.
 */
const migrations = {
	postgres: `
CREATE TABLE entries (
	id UUID PRIMARY KEY,
	ledger_id TEXT NOT NULL,
	number INTEGER NOT NULL CHECK (number > 0),
	rank SMALLINT NOT NULL CHECK (rank BETWEEN 1 AND 5),
	code BIGINT NOT NULL UNIQUE,
	slot INTEGER NOT NULL,
	tally INTEGER NOT NULL,
	rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
	weight NUMERIC(2, 1) NOT NULL,
	label TEXT NOT NULL,
	UNIQUE (ledger_id, number) INCLUDE (rating),
	UNIQUE (ledger_id, rank)
);
CREATE UNIQUE INDEX entries_slot ON entries (slot) WHERE slot > 100;
CREATE UNIQUE INDEX entries_tally ON entries (tally, lower(label));
CREATE UNIQUE INDEX entries_label ON entries (lower(label));
CREATE TABLE stamps (id UUID PRIMARY KEY, serial NUMERIC(3, 0) NOT NULL UNIQUE);
CREATE TABLE scores (id UUID PRIMARY KEY, score DOUBLE PRECISION NOT NULL UNIQUE);
CREATE TABLE badges (id UUID PRIMARY KEY, flag TEXT NOT NULL UNIQUE CHECK (flag IN ('only', 'spare')));
CREATE TABLE tickets (id UUID PRIMARY KEY, seq INTEGER GENERATED BY DEFAULT AS IDENTITY UNIQUE);
CREATE TABLE shelves (id UUID PRIMARY KEY, bay INTEGER, n INTEGER NOT NULL, UNIQUE NULLS NOT DISTINCT (bay, n));
INSERT INTO entries VALUES ('00000000-0000-4000-8000-000000000001', 'imported', 7, 1, 41, 5, 5, 1, 1.0, 'imported');
INSERT INTO stamps VALUES ('00000000-0000-4000-8000-000000000002', 999);
INSERT INTO scores VALUES ('00000000-0000-4000-8000-000000000003', 'Infinity');
INSERT INTO badges VALUES ('00000000-0000-4000-8000-000000000004', 'only');
`,
	sqlite: `
CREATE TABLE entries (
	id UUID PRIMARY KEY,
	ledger_id TEXT NOT NULL,
	number INTEGER NOT NULL CHECK (number > 0),
	rank SMALLINT NOT NULL CHECK (rank BETWEEN 1 AND 5),
	code BIGINT NOT NULL UNIQUE,
	slot INTEGER NOT NULL,
	tally INTEGER NOT NULL,
	rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
	weight REAL NOT NULL CHECK (weight < 10),
	label TEXT NOT NULL,
	UNIQUE (ledger_id, number),
	UNIQUE (ledger_id, rank)
);
CREATE UNIQUE INDEX entries_slot ON entries (slot) WHERE slot > 100;
CREATE UNIQUE INDEX entries_tally ON entries (tally, lower(label));
CREATE UNIQUE INDEX entries_label ON entries (lower(label));
CREATE TABLE stamps (id UUID PRIMARY KEY, serial INTEGER NOT NULL UNIQUE);
CREATE TABLE scores (id UUID PRIMARY KEY, score REAL NOT NULL UNIQUE);
CREATE TABLE badges (id UUID PRIMARY KEY, flag TEXT NOT NULL UNIQUE CHECK (flag IN ('only', 'spare')));
INSERT INTO entries VALUES ('00000000-0000-4000-8000-000000000001', 'imported', 7, 1, 41, 5, 5, 1, 1.0, 'imported');
INSERT INTO stamps VALUES ('00000000-0000-4000-8000-000000000002', 9007199254740991);
INSERT INTO scores VALUES ('00000000-0000-4000-8000-000000000003', 9e999);
INSERT INTO badges VALUES ('00000000-0000-4000-8000-000000000004', 'only');
`,
}

const directory = mkdtempSync(join(tmpdir(), 'fabrika-db-seeding-numbers-'))
for (const dialect of ['postgres', 'sqlite'] as const) {
	mkdirSync(join(directory, dialect))
	writeFileSync(join(directory, dialect, '20261103120000_entries.sql'), migrations[dialect])
}
const label = 'seeding-numbers.test.ts'
const sqlite = await sqliteDatabase({ migrations: join(directory, 'sqlite'), label })
const postgres = await postgresDatabase({ migrations: join(directory, 'postgres'), label })

afterAll(async () => {
	await sqlite.close()
	await postgres?.close()
	rmSync(directory, { recursive: true, force: true })
})

/** How each dialect hands back a sample of `bigint` and of a small numeric: Postgres as text, SQLite as a number. */
const forms = {
	SQLite: { code: (value: number) => value, weight: 1 },
	Postgres: { code: (value: number) => String(value), weight: '1' },
}

for (const [dialect, database] of [['SQLite', sqlite], ['Postgres', postgres]] as const) {
	describe.skipIf(database === null)(`the numbers the isolation seed writes, on ${dialect}`, () => {
		const form = forms[dialect]
		// Left alone: no unique index covers rating and weight; slot's is partial, tally's holds an expression.
		const fixed = { slot: 1, tally: 1, rating: 1, weight: form.weight }

		test('a unique number takes the next above the largest of its group; any other number is 1', async () => {
			if (database === null) return
			const worlds = await database.seedWorlds(tables, 'entries')
			// Each world lies in a fresh ledger, so its number and rank are 1; the code is unique across the table, above
			// the migration's 41; rating is only INCLUDEd in the number's index on Postgres.
			expect(worlds.own.updates).toEqual({ number: 1, rank: 1, code: form.code(42), ...fixed })
			expect(worlds.other.updates).toEqual({ number: 1, rank: 1, code: form.code(43), ...fixed })
			// Beside the own row, in its ledger: the next after its 1. The index on lower(label) refuses nothing here.
			const beside = await database.sampleInsert(tables, 'entries', worlds.own)
			expect(beside).toEqual({ number: 2, rank: 2, code: form.code(44), ...fixed, label: expect.any(String) })
			// Taken again before an insert, a sample repeats the numbers: the caller inserts one before the next.
			expect(await database.sampleInsert(tables, 'entries', worlds.own)).toMatchObject({ number: 2, code: form.code(44) })
			// With no row to lie beside, the ledger is unknown and the group is the whole column.
			expect(await database.sampleInsert(tables, 'entries')).toMatchObject({ number: 8, rank: 2 })
		})

		test('a bounded CHECK, on a column a composite unique index covers or none does, keeps passing however many rows the seed writes', async () => {
			if (database === null) return
			for (let round = 0; round < 12; round++) await database.seedWorlds(tables, 'entries')
			const worlds = await database.seedWorlds(tables, 'entries')
			expect([worlds.own.updates['rank'], worlds.own.updates['rating'], worlds.own.updates['weight']]).toEqual([1, 1, form.weight])
			expect(await database.sampleInsert(tables, 'entries', worlds.own)).toMatchObject({ rank: 2, rating: 1 })
		})

		test('a unique number whose type holds none above the largest, or whose largest is no finite number, is a seed limit naming the index', async () => {
			if (database === null) return
			const stamped = database.seedWorlds(tables, 'stamps')
			await expect(stamped).rejects.toThrow(SeedLimitError)
			await expect(stamped).rejects.toThrow(/the unique index \S+ of stamps: serial holds no number above its largest value/)
			await expect(database.seedWorlds(tables, 'scores')).rejects.toThrow(/the unique index \S+ of scores: score holds no number above/)
		})

		test('a value another row holds where the seed writes it is a seed limit naming the index', async () => {
			if (database === null) return
			const badged = database.seedWorlds(tables, 'badges')
			await expect(badged).rejects.toThrow(SeedLimitError)
			await expect(badged).rejects.toThrow(/the unique index \S+ of badges: it writes a sample of each column's type there, which another row holds/)
		})
	})
}

describe.skipIf(postgres === null)('the numbers the isolation seed writes, on Postgres only', () => {
	test('the update sample of a number the database filled is taken once both worlds are written', async () => {
		if (postgres === null) return
		// The identity gives the own row 1 and the other 2: a sample taken between the two would be 2, the other's.
		const worlds = await postgres.seedWorlds(tables, 'tickets')
		expect([worlds.own.updates['seq'], worlds.other.updates['seq']]).toEqual([3, 3])
	})

	test('a NULLS NOT DISTINCT index groups the rows its null key column holds', async () => {
		if (postgres === null) return
		const worlds = await postgres.seedWorlds(tables, 'shelves')
		expect([worlds.own.updates['n'], worlds.other.updates['n']]).toEqual([1, 2])
	})
})
