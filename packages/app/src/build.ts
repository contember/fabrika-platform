// @fabrika/app/build — the generated entrypoint of a contract application, which `fabrika app build` writes. It is
// the only module that reads `process.env` and the only caller of `boot`, through the runtime adapter, and it imports
// the application only after the adapter took the framework's variables out of the process.

import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'

/** An application root with this file is a contract application. The paths equal `@fabrika/check`'s layout. */
export const CONTRACT_FILE = 'fabrika.contract.ts'

/** Relative to the application root. */
export const GENERATED_ENTRY_FILE = 'fabrika/entry.generated.ts'

/** The module whose default export is `serve(contract, …)`, relative to the application root. */
export const IMPLEMENTATION_FILE = 'src/app.ts'

/** The application's migrations as a module, relative to the application root: a Worker reads no file system. */
export const GENERATED_MIGRATIONS_FILE = 'fabrika/migrations.generated.ts'

/** Where an application keeps its migrations, relative to its root; `fabrika db new` writes there. */
export const MIGRATIONS_DIRECTORY = 'db/migrations'

export type EntryRuntime = 'bun' | 'cloudflare'

export * from './build-recipe.js'

// In a module of their own, which the Worker imports without this one's file system.
export {
	CLOUDFLARE_APPLICATION_BINDING,
	CLOUDFLARE_APPLICATION_CLASS,
	CLOUDFLARE_ASSETS_BINDING,
	CLOUDFLARE_FILES_BINDING,
} from './cloudflare/names.js'

const HEADER = '// @generated by `fabrika app build` from src/app.ts. Do not edit: every build rewrites it.'

/** The entrypoint source for one runtime. */
export function generatedEntry(runtime: EntryRuntime): string {
	switch (runtime) {
		case 'bun':
			return [
				HEADER,
				"import { markProductionProcess, serveContract } from '@fabrika/app/bun'",
				'',
				'// The test kits refuse to load from here on; the application is imported only after the framework took its variables.',
				'markProductionProcess()',
				"await serveContract(() => import('../src/app'), process.env)",
				'',
			].join('\n')
		case 'cloudflare':
			return [
				HEADER,
				"import { createContractWorker, markProductionProcess } from '@fabrika/app/cloudflare'",
				"import { migrations } from './migrations.generated'",
				'',
				"export { FabrikaApplication } from '@fabrika/app/cloudflare'",
				'',
				'// The test kits refuse to load from here on; the object imports the application only after the framework took its variables.',
				'markProductionProcess()',
				"export default createContractWorker(() => import('../src/app'), { migrations })",
				'',
			].join('\n')
	}
}

/** Writes the entrypoint under `root` and returns its path; the Cloudflare one also writes the migrations module it imports. */
export async function writeGeneratedEntry(root: string, runtime: EntryRuntime): Promise<string> {
	const path = join(root, GENERATED_ENTRY_FILE)
	await mkdir(dirname(path), { recursive: true })
	await writeFile(path, generatedEntry(runtime))
	if (runtime === 'cloudflare') {
		await writeGeneratedMigrations(root)
	}
	return path
}

/** The application's migrations under `root`, every `.sql` file of `db/migrations` by name; none without the directory. */
export async function applicationMigrations(root: string): Promise<readonly { readonly name: string; readonly sql: string }[]> {
	const directory = join(root, MIGRATIONS_DIRECTORY)
	let names: string[]
	try {
		names = await readdir(directory)
	} catch (error) {
		if (error instanceof Error && 'code' in error && error.code === 'ENOENT') {
			return []
		}
		throw error
	}
	const files = names.filter((name) => name.endsWith('.sql')).sort((left, right) => left < right ? -1 : left > right ? 1 : 0)
	return await Promise.all(files.map(async (name) => ({ name, sql: await readFile(join(directory, name), 'utf8') })))
}

/** The migrations module source: the files' names and texts, verbatim, so their checksums stay the files'. */
export function generatedMigrations(migrations: readonly { readonly name: string; readonly sql: string }[]): string {
	return [
		`// @generated by \`fabrika app build\` from ${MIGRATIONS_DIRECTORY}. Do not edit: every build rewrites it.`,
		'',
		`export const migrations: readonly { readonly name: string; readonly sql: string }[] = ${JSON.stringify(migrations, null, '\t')}`,
		'',
	].join('\n')
}

/** Writes the migrations module under `root` and returns its path. */
export async function writeGeneratedMigrations(root: string): Promise<string> {
	const path = join(root, GENERATED_MIGRATIONS_FILE)
	await mkdir(dirname(path), { recursive: true })
	await writeFile(path, generatedMigrations(await applicationMigrations(root)))
	return path
}
