// The vendored snapshot module `fabrika connect add` and `pull` write: an export's description as zod source in the
// contract subset, so `@fabrika/check` reads it as a literal and `describeSnapshot` reads back the shapes it came from.
// The description arrives from another application, so every value is written as a literal the parser cannot misread.

import type { ExportDescription, NumberShape, SchemaShape, StringShape } from '@fabrika/auth-core'
import { ContractError } from './problems'

/** The directory, relative to the application root, that holds the vendored snapshots. */
export const SNAPSHOT_DIRECTORY = 'fabrika/connect'

const HEADER = '// @generated by `fabrika connect` from the export description its owner serves. Do not edit: `fabrika connect pull` rewrites it.'

export interface SnapshotNames {
	/** Relative to the application root: `fabrika/connect/catalog.products.v1.ts`. */
	readonly file: string
	/** The snapshot const: `catalogProductsV1`. */
	readonly snapshot: string
	/** The digest const the contract's import names: `catalogProductsV1Digest`. */
	readonly digest: string
}

function capitalized(word: string): string {
	return `${word.slice(0, 1).toUpperCase()}${word.slice(1)}`
}

/** The file and the identifiers of the snapshot of `app`'s export `name` at `version`. */
export function snapshotNames(app: string, name: string, version: number): SnapshotNames {
	const [first = '', ...rest] = app.split('-')
	const appWord = `${first}${rest.map(capitalized).join('')}`
	const snapshot = `${/^[a-z]/.test(appWord) ? appWord : `app${appWord}`}${capitalized(name)}V${version}`
	return { file: `${SNAPSHOT_DIRECTORY}/${app}.${name}.v${version}.ts`, snapshot, digest: `${snapshot}Digest` }
}

/** The snapshot module of `description`. Throws `ContractError` for a shape no zod source in the subset writes. */
export function snapshotSource(description: ExportDescription): string {
	const names = snapshotNames(description.app, description.export, description.version)
	const procedures = Object.entries(description.procedures).map(([path, procedure]) =>
		[
			`\t\t${key(path)}: {`,
			`\t\t\tinput: ${procedure.input === null ? 'null' : schemaSource(procedure.input, path)},`,
			`\t\t\toutput: ${schemaSource(procedure.output, path)},`,
			'\t\t},',
		].join('\n')
	)
	return [
		HEADER,
		"import { z } from 'zod/v4'",
		'',
		`export const ${names.digest} = ${literal(description.digest)}`,
		'',
		`export const ${names.snapshot} = {`,
		`\tapp: ${literal(description.app)},`,
		`\texport: ${literal(description.export)},`,
		`\tversion: ${number(description.version)},`,
		`\taudience: ${literal(description.audience)},`,
		`\tdigest: ${names.digest},`,
		'\tprocedures: {',
		...procedures,
		'\t},',
		'} as const',
		'',
	].join('\n')
}

/**
 * A single-quoted string literal with the value's own characters. JSON escapes every `"` as `\"` and every `\` as a
 * pair, so turning each `\"` back into `"` touches only a quote; a `'` is then escaped.
 */
function literal(value: string | number | boolean | null): string {
	if (typeof value !== 'string') {
		return typeof value === 'number' ? number(value) : String(value)
	}
	return `'${JSON.stringify(value).slice(1, -1).replaceAll('\\"', '"').replaceAll("'", "\\'")}'`
}

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/

/** `__proto__` as a literal key sets the object's prototype instead of a property, quoted or not. */
function key(name: string): string {
	if (name === '__proto__') {
		throw new ContractError(['a field or procedure named __proto__ has no object-literal key'])
	}
	return IDENTIFIER.test(name) ? name : literal(name)
}

function number(value: number): string {
	if (!Number.isFinite(value)) {
		throw new ContractError([`the number ${value} has no literal`])
	}
	return Object.is(value, -0) ? '0' : String(value)
}

function schemaSource(shape: SchemaShape, where: string): string {
	switch (shape.type) {
		case 'string':
			return stringSource(shape, where)
		case 'number':
			return numberSource(shape)
		case 'boolean':
		case 'null':
			return `z.${shape.type}()`
		case 'literal':
			return `z.literal(${literal(shape.value)})`
		case 'enum':
			if (shape.values.length === 0) {
				throw new ContractError([`procedure '${where}': an enum without values has no zod source`])
			}
			return `z.enum([${shape.values.map(literal).join(', ')}])`
		case 'array':
			return `z.array(${schemaSource(shape.items, where)})${bound('min', shape.minItems)}${bound('max', shape.maxItems)}`
		case 'tuple': {
			const items = `[${shape.items.map((item) => schemaSource(item, where)).join(', ')}]`
			return shape.rest === null ? `z.tuple(${items})` : `z.tuple(${items}, ${schemaSource(shape.rest, where)})`
		}
		case 'record':
			return `z.record(${schemaSource(shape.key, where)}, ${schemaSource(shape.value, where)})`
		case 'object': {
			const fields = Object.entries(shape.fields).map(([name, field]) => `${key(name)}: ${schemaSource(field, where)}`)
			return `z.strictObject({ ${fields.join(', ')} })`
		}
		case 'optional':
		case 'nullable':
			return `z.${shape.type}(${schemaSource(shape.inner, where)})`
		case 'union':
			return `z.union([${shape.options.map((option) => schemaSource(option, where)).join(', ')}])`
		case 'token':
			// The build refuses a signed token in an export, so no description it vendors holds one.
			throw new ContractError([`procedure '${where}': a signed token has no zod source in a connector snapshot`])
		case 'file':
			throw new ContractError([`procedure '${where}': an export carries no file`])
	}
}

function bound(method: string, value: number | null): string {
	return value === null ? '' : `.${method}(${number(value)})`
}

const ISO_FORMATS: ReadonlySet<string> = new Set(['datetime', 'date', 'time', 'duration'])

function stringSource(shape: StringShape, where: string): string {
	const base = shape.format === null ? 'z.string()' : ISO_FORMATS.has(shape.format) ? `z.iso.${shape.format}()` : `z.${shape.format}()`
	const affixes = (['startsWith', 'endsWith', 'includes'] as const).map((field) => {
		const value = shape[field]
		return value === null ? '' : `.${field}(${literal(value)})`
	})
	return `${base}${bound('min', shape.minLength)}${bound('max', shape.maxLength)}${patternSource(shape.pattern, where)}${affixes.join('')}`
}

/**
 * A pattern is written as a regular-expression literal, which only `.regex()` takes. `RegExp#source` escapes every `/`
 * and line terminator, so a pattern equal to its own normalized source cannot end the literal early.
 */
function patternSource(pattern: string | null, where: string): string {
	if (pattern === null) {
		return ''
	}
	let normalized: string
	try {
		normalized = new RegExp(pattern).source
	} catch {
		normalized = ''
	}
	if (normalized !== pattern || pattern === '(?:)') {
		throw new ContractError([`procedure '${where}': the pattern is not one regular-expression literal`])
	}
	return `.regex(/${pattern}/)`
}

function numberSource(shape: NumberShape): string {
	const min = shape.min === null ? '' : `.${shape.exclusiveMin ? 'gt' : 'gte'}(${number(shape.min)})`
	const max = shape.max === null ? '' : `.${shape.exclusiveMax ? 'lt' : 'lte'}(${number(shape.max)})`
	return `${shape.int ? 'z.int()' : 'z.number()'}${min}${max}${bound('multipleOf', shape.multipleOf)}`
}
