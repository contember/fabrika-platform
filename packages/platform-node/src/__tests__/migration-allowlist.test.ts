import { describe, expect, test } from 'bun:test'
import { disallowedStatement } from '../migration-allowlist.js'

const SCHEMA = 'app_notes'
const refusal = (sql: string): string | undefined => disallowedStatement(sql, SCHEMA)?.statement

describe('the statements an application migration may hold', () => {
	test('allows tables, indexes, enum types, drops, comments and backfills', () => {
		const sql = [
			"CREATE TYPE stage AS ENUM ('open', 'won');",
			'CREATE TYPE "Mood" AS ENUM (\'calm\');',
			"ALTER TYPE stage ADD VALUE IF NOT EXISTS 'lost';",
			"ALTER TYPE stage RENAME VALUE 'won' TO 'closed';",
			'CREATE TABLE IF NOT EXISTS deals (id uuid PRIMARY KEY DEFAULT gen_random_uuid(), n bigint GENERATED ALWAYS AS IDENTITY, stage stage);',
			"CREATE TABLE copy (LIKE deals EXCLUDING ALL, including text, CHECK (including <> ''));",
			'CREATE TABLE app_notes.qualified (id text);',
			'CREATE INDEX deals_stage ON deals (stage) WHERE stage IS NOT NULL;',
			'CREATE UNIQUE INDEX deals_lower ON deals (lower(id::text));',
			'ALTER INDEX IF EXISTS deals_stage RENAME TO deals_by_stage;',
			"ALTER TABLE deals ADD COLUMN note text, ALTER COLUMN note SET DEFAULT '', DROP CONSTRAINT IF EXISTS deals_check;",
			"ALTER TABLE ONLY deals ADD CONSTRAINT deals_note CHECK (note <> 'x') NOT VALID, VALIDATE CONSTRAINT deals_note;",
			'ALTER TABLE deals ALTER note TYPE varchar(80) USING btrim(note), ALTER COLUMN note SET NOT NULL, ALTER note DROP NOT NULL;',
			'ALTER TABLE deals ALTER COLUMN note DROP DEFAULT, ADD UNIQUE (note), ADD PRIMARY KEY (id), DROP COLUMN IF EXISTS old;',
			'ALTER TABLE deals ALTER COLUMN counter ADD GENERATED ALWAYS AS IDENTITY, ALTER counter SET GENERATED BY DEFAULT, ALTER counter RESTART;',
			'ALTER TABLE deals ALTER COLUMN counter DROP IDENTITY IF EXISTS;',
			'ALTER TABLE deals RENAME COLUMN note TO memo;',
			'ALTER TABLE deals RENAME CONSTRAINT deals_note TO deals_memo;',
			'ALTER TABLE IF EXISTS deals RENAME TO opportunities;',
			"COMMENT ON COLUMN opportunities.memo IS 'CREATE FUNCTION f';",
			"INSERT INTO deals (stage) VALUES ('open') ON CONFLICT (id) DO UPDATE SET stage = excluded.stage;",
			'UPDATE deals SET note = d.note FROM deals_old d, other_deals o WHERE deals.id = d.id AND o.id IS DISTINCT FROM d.id;',
			'UPDATE deals SET year = EXTRACT(year FROM d.created_at) FROM deals_old d WHERE d.id = deals.id;',
			'INSERT INTO deals (stage) SELECT o.stage FROM deals_old o JOIN app_notes.extra x ON x.id = o.id;',
			'DELETE FROM deals USING deals_old o WHERE deals.id = o.id RETURNING deals.id;',
			'TRUNCATE TABLE ONLY deals, deals_old RESTART IDENTITY CASCADE;',
			'DROP INDEX deals_stage;',
			'DROP TABLE copy;',
			'DROP TRIGGER IF EXISTS legacy ON deals;',
			'DROP FUNCTION IF EXISTS legacy();',
			'DROP ROUTINE IF EXISTS legacy_routine;',
			'DROP STATISTICS IF EXISTS legacy_stats;',
			'DROP EXTENSION IF EXISTS citext;',
			'-- CREATE TRIGGER t',
		].join('\n')
		expect(disallowedStatement(sql, SCHEMA)).toBeUndefined()
	})

	test('refuses every other statement', () => {
		for (
			const [sql, statement] of [
				['CREATE FUNCTION f() RETURNS int LANGUAGE sql AS $$ SELECT 1 $$', 'CREATE FUNCTION'],
				['create or replace function f() returns int language sql as $$ select 1 $$', 'CREATE OR'],
				['CREATE TRIGGER t AFTER UPDATE ON a FOR EACH ROW EXECUTE FUNCTION f()', 'CREATE TRIGGER'],
				['CREATE RULE r AS ON UPDATE TO a DO ALSO DELETE FROM b', 'CREATE RULE'],
				['CREATE VIEW v AS SELECT 1', 'CREATE VIEW'],
				['CREATE MATERIALIZED VIEW v AS SELECT 1', 'CREATE MATERIALIZED'],
				['CREATE POLICY p ON a USING (true)', 'CREATE POLICY'],
				['CREATE EXTENSION dblink', 'CREATE EXTENSION'],
				['CREATE DOMAIN d AS int CHECK (VALUE > 0)', 'CREATE DOMAIN'],
				['CREATE SEQUENCE s', 'CREATE SEQUENCE'],
				['CREATE SCHEMA s', 'CREATE SCHEMA'],
				['CREATE TEMP TABLE scratch (id text)', 'CREATE TEMP'],
				['CREATE UNLOGGED TABLE scratch (id text)', 'CREATE UNLOGGED'],
				['CREATE TYPE r AS RANGE (subtype = int4)', 'CREATE TYPE other than AS ENUM'],
				['CREATE TYPE pair AS (a int, b int)', 'CREATE TYPE other than AS ENUM'],
				['ALTER TYPE stage OWNER TO someone', 'ALTER TYPE other than ADD VALUE or RENAME VALUE'],
				['ALTER INDEX i SET TABLESPACE fast', 'ALTER INDEX other than RENAME TO'],
				['DROP SCHEMA s CASCADE', 'DROP SCHEMA'],
				['DROP OWNED BY someone', 'DROP OWNED'],
				['DROP EXTENSION citext CASCADE', 'DROP EXTENSION … CASCADE'],
				['DO $$ BEGIN PERFORM 1; END $$', 'DO'],
				['COPY a FROM PROGRAM \'psql -c "CREATE FUNCTION f() RETURNS int AS $$ SELECT 1 $$ LANGUAGE sql"\'', 'COPY'],
				['SELECT 1', 'SELECT'],
				['WITH x AS (DELETE FROM a RETURNING *) SELECT 1', 'WITH'],
				['WITH x AS (SELECT 1) INSERT INTO a SELECT * FROM x', 'WITH'],
				['MERGE INTO a USING b ON a.id = b.id WHEN MATCHED THEN DELETE', 'MERGE'],
				['PREPARE q AS INSERT INTO a VALUES (1)', 'PREPARE'],
				['EXECUTE q', 'EXECUTE'],
				['CALL p()', 'CALL'],
				['SET search_path TO public', 'SET'],
				['GRANT SELECT ON a TO PUBLIC', 'GRANT'],
				['REVOKE ALL ON a FROM PUBLIC', 'REVOKE'],
				['ALTER DEFAULT PRIVILEGES GRANT SELECT ON TABLES TO PUBLIC', 'ALTER DEFAULT'],
				['ALTER ROLE CURRENT_USER SET standard_conforming_strings = off', 'ALTER ROLE'],
				['EXPLAIN ANALYZE CREATE MATERIALIZED VIEW v AS SELECT 1', 'EXPLAIN'],
				['ANALYZE a', 'ANALYZE'],
				['(SELECT 1)', '('],
			] as const
		) {
			expect(refusal(sql)).toBe(statement)
		}
	})

	test('CREATE TABLE is a column list and nothing else', () => {
		for (
			const [sql, statement] of [
				['CREATE TABLE b (LIKE a INCLUDING ALL)', 'CREATE TABLE … LIKE … INCLUDING'],
				['CREATE TABLE b (id text, LIKE a INCLUDING DEFAULTS)', 'CREATE TABLE … LIKE … INCLUDING'],
				['CREATE TABLE b AS SELECT * FROM a', 'CREATE TABLE other than a column list'],
				['CREATE TABLE b (id) AS SELECT 1', 'CREATE TABLE … AS'],
				['CREATE TABLE b (id text) INHERITS (a)', 'CREATE TABLE … INHERITS'],
				['CREATE TABLE b PARTITION OF a DEFAULT', 'CREATE TABLE other than a column list'],
				['CREATE TABLE b (id text) PARTITION BY RANGE (id)', 'CREATE TABLE … PARTITION'],
				['CREATE TABLE b OF pair', 'CREATE TABLE other than a column list'],
				['CREATE TABLE b (id text) TABLESPACE fast', 'CREATE TABLE … TABLESPACE'],
				['CREATE TABLE b (id text) WITH (fillfactor = 70)', 'CREATE TABLE … WITH'],
				['CREATE TABLE b (id text) USING heap', 'CREATE TABLE … USING'],
			] as const
		) {
			expect(refusal(sql)).toBe(statement)
		}
	})

	test('ALTER TABLE takes only column, constraint and rename clauses', () => {
		for (
			const [sql, statement] of [
				['ALTER TABLE ALL IN TABLESPACE pg_default SET TABLESPACE fast', 'ALTER TABLE ALL IN TABLESPACE'],
				['ALTER TABLE a DISABLE TRIGGER ALL', 'ALTER TABLE … DISABLE'],
				['ALTER TABLE a ENABLE ALWAYS TRIGGER t', 'ALTER TABLE … ENABLE'],
				['ALTER TABLE a ENABLE RULE r', 'ALTER TABLE … ENABLE'],
				['ALTER TABLE a ENABLE ROW LEVEL SECURITY', 'ALTER TABLE … ENABLE'],
				['ALTER TABLE a INHERIT b', 'ALTER TABLE … INHERIT'],
				['ALTER TABLE a NO INHERIT b', 'ALTER TABLE … NO'],
				['ALTER TABLE a ATTACH PARTITION b DEFAULT', 'ALTER TABLE … ATTACH'],
				['ALTER TABLE a DETACH PARTITION b', 'ALTER TABLE … DETACH'],
				['ALTER TABLE a OF pair', 'ALTER TABLE … OF'],
				['ALTER TABLE a SET TABLESPACE fast', 'ALTER TABLE … SET'],
				['ALTER TABLE a SET ACCESS METHOD heap', 'ALTER TABLE … SET'],
				['ALTER TABLE a SET SCHEMA elsewhere', 'ALTER TABLE … SET'],
				['ALTER TABLE a OWNER TO someone', 'ALTER TABLE … OWNER'],
				['ALTER TABLE a REPLICA IDENTITY FULL', 'ALTER TABLE … REPLICA'],
				['ALTER TABLE a SET (fillfactor = 70)', 'ALTER TABLE … SET'],
				['ALTER TABLE a ADD COLUMN b text, CLUSTER ON a_pkey', 'ALTER TABLE … CLUSTER'],
				['ALTER TABLE a ADD EXCLUDE USING gist (b WITH &&)', 'ALTER TABLE … ADD EXCLUDE'],
				['ALTER TABLE a ALTER CONSTRAINT c DEFERRABLE', 'ALTER TABLE … ALTER'],
				['ALTER TABLE a ALTER COLUMN b SET STATISTICS 100', 'ALTER TABLE … ALTER COLUMN … SET'],
				['ALTER TABLE a ALTER COLUMN b SET EXPRESSION AS (1)', 'ALTER TABLE … ALTER COLUMN … SET'],
			] as const
		) {
			expect(refusal(sql)).toBe(statement)
		}
	})

	test('names no schema but the application’s own, pg_catalog included', () => {
		for (
			const [sql, statement] of [
				['UPDATE pg_catalog.pg_proc SET prosrc = 1', 'UPDATE reaching the schema pg_catalog'],
				["UPDATE pg_proc SET prosrc = '' WHERE proname = 'lower'", 'UPDATE reaching the schema pg_catalog'],
				['INSERT INTO other.t VALUES (1)', 'INSERT reaching the schema other'],
				['INSERT INTO t SELECT * FROM other.t', 'INSERT reaching the schema other'],
				['INSERT INTO t SELECT x FROM a, other.t', 'INSERT reaching the schema other'],
				['INSERT INTO t SELECT x FROM a JOIN other.t ON true', 'INSERT reaching the schema other'],
				['INSERT INTO t SELECT pg_catalog.lo_unlink(1)', 'INSERT reaching the schema pg_catalog'],
				['UPDATE t SET a = other.f(a)', 'UPDATE reaching the schema other'],
				["UPDATE t SET a = '1'::other.sneaky", 'UPDATE reaching the schema other'],
				['UPDATE t SET a = other.t.a FROM other.t', 'UPDATE reaching the schema other'],
				['DELETE FROM t USING a, other.t', 'DELETE reaching the schema other'],
				['DELETE FROM ONLY other.t', 'DELETE reaching the schema other'],
				['UPDATE t SET a = (SELECT b FROM other.t LIMIT 1)', 'UPDATE reaching the schema other'],
				['CREATE INDEX i ON other.t (a)', 'CREATE INDEX naming the schema other'],
				['CREATE INDEX i ON t (pg_catalog.lower(a))', 'CREATE INDEX naming the schema pg_catalog'],
				['CREATE TABLE t (a text REFERENCES other.t (id))', 'CREATE TABLE naming the schema other'],
				['CREATE TABLE t (a other.citext)', 'CREATE TABLE naming the schema other'],
				['ALTER TABLE t ALTER a TYPE int USING other.f(a)', 'ALTER TABLE naming the schema other'],
				['DROP FUNCTION other.f()', 'DROP FUNCTION naming the schema other'],
				['TRUNCATE other.t', 'TRUNCATE naming the schema other'],
				['ALTER INDEX other.i RENAME TO j', 'ALTER INDEX naming the schema other'],
			] as const
		) {
			expect(refusal(sql)).toBe(statement)
		}
	})

	test('a comment ended by a lone carriage return hides no statement', () => {
		const sql = 'CREATE TABLE a (id text); -- a note\rCREATE FUNCTION f() RETURNS int LANGUAGE sql AS $$ SELECT 1 $$'
		expect(refusal(sql)).toBe('CREATE FUNCTION')
	})

	test('a dollar quote with a long tag and an unmatched parenthesis hides no statement', () => {
		const tag = `$${'t'.repeat(70)}$`
		const sql = `CREATE TABLE a (id text);\nCOMMENT ON TABLE a IS ${tag} ( ${tag};\nCREATE FUNCTION f() RETURNS int LANGUAGE sql AS $$ SELECT 1 $$`
		expect(disallowedStatement(sql, SCHEMA)).toEqual({ statement: 'CREATE FUNCTION', line: 3 })
	})

	test('a no-break space or a BOM before an E string hides no statement', () => {
		for (const space of [' ', '﻿']) {
			const sql = `CREATE TABLE a (c text DEFAULT ${space}E'\\'); CREATE FUNCTION f() RETURNS int LANGUAGE sql AS $$ SELECT 1 $$; --')`
			expect(refusal(sql)).toBe('CREATE FUNCTION')
		}
	})

	test('names the line of the refused statement', () => {
		expect(disallowedStatement('CREATE TABLE a (id text);\n\nCREATE TRIGGER t AFTER UPDATE ON a EXECUTE FUNCTION f()', SCHEMA)).toEqual({
			statement: 'CREATE TRIGGER',
			line: 3,
		})
	})
})
