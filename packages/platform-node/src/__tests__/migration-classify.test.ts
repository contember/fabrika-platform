const classify = (sql: string, functions: readonly string[] = []) => classifyMigration(sql, SCHEMA, { file: FILE, functions: new Set(functions) })
const refusal = (sql: string, functions: readonly string[] = []): string | undefined => classify(sql, functions).refused[0]?.reason
const deviationKeys = (sql: string, functions: readonly string[] = []): string[] =>
	classify(sql, functions).deviations.map((deviation) => `${deviation.kind} ${deviation.object}`)

